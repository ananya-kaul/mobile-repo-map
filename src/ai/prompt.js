/**
 * Turns the static-analysis summary, the retrieved excerpts and the question into a
 * provider-neutral { system, user } pair.
 */

const SYSTEM = `You are an expert mobile engineer (Flutter/Dart and iOS/Swift, SwiftUI and UIKit) helping a developer understand a codebase they have never seen before.

You are given:
1. An architecture summary produced by static analysis of the repository (screens, navigation, API calls, modules, risks). It is generated by heuristics, so treat it as a strong hint rather than ground truth.
2. Excerpts of the source files that best match the question. Every code line is prefixed with its original line number ("  42| code"). A line such as "// … (12 lines omitted)" marks code that was cut, not code that is missing from the repository.

How to answer:
- Answer the question concretely: name the actual screens, classes, methods, routes, endpoints and state objects involved, in the order things happen.
- Cite evidence as path:line (for example lib/checkout/checkout_service.dart:42), using the line numbers shown in the excerpts. Only cite lines you can see.
- When something the answer depends on is not visible in the provided context (an omitted region, a file that was not included, server-side behaviour), say so plainly and name the file or symbol the reader should open next. Do not invent code, endpoints or file names.
- Prefer short sections with headings and bullet points over long paragraphs. A brief step-by-step flow is often the clearest shape.
- Point out anything surprising or risky you notice along the way (error handling gaps, duplicated logic, platform differences), briefly.`;

const LANG_BY_EXT = {
  dart: 'dart', swift: 'swift', m: 'objectivec', mm: 'objectivec', h: 'objectivec',
  kt: 'kotlin', java: 'java', js: 'javascript', ts: 'typescript', json: 'json',
  yaml: 'yaml', yml: 'yaml', plist: 'xml', xml: 'xml', gradle: 'groovy',
};

function languageOf(path) {
  const m = /\.([A-Za-z0-9]+)$/.exec(path || '');
  return (m && LANG_BY_EXT[m[1].toLowerCase()]) || '';
}

/** A backtick fence longer than any backtick run inside `text`, so the block cannot be closed early. */
function fenceFor(text) {
  let longest = 0;
  for (const run of String(text).match(/`+/g) || []) longest = Math.max(longest, run.length);
  return '`'.repeat(Math.max(3, longest + 1));
}

/**
 * @param {{ question: string, contextMd?: string, snippets?: Array<{ path: string, text: string }> }} input
 * @returns {{ system: string, user: string }}
 */
export function buildPrompt({ question, contextMd, snippets = [] }) {
  const parts = [];

  parts.push('# Architecture summary (from static analysis)');
  parts.push((contextMd && String(contextMd).trim()) || '_No architecture summary was provided._');

  parts.push('# Relevant source excerpts');
  if (!snippets.length) {
    parts.push('_No source files matched the question; answer from the architecture summary and say what you would need to see._');
  } else {
    parts.push(`${snippets.length} file${snippets.length === 1 ? '' : 's'}, ranked by relevance. Line numbers are original; "// …" marks omitted lines.`);
    for (const s of snippets) {
      const fence = fenceFor(s.text);
      const lang = languageOf(s.path);
      parts.push(`## ${s.path}\n${fence}${lang ? `${lang} ` : ''}${s.path}\n${String(s.text).replace(/\n+$/, '')}\n${fence}`);
    }
  }

  parts.push('# Question');
  parts.push(String(question || '').trim());

  return { system: SYSTEM, user: `${parts.join('\n\n')}\n` };
}
